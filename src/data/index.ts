// ─── EGYPTIAN PRICE FORMATTER ─────────────────────────────────────────────────
export function formatEGP(price: number): string {
  return new Intl.NumberFormat("ar-EG", {
    style: "currency",
    currency: "EGP",
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(price);
}

